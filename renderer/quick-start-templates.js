(function quickStartTemplatesFactory(root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) {
    module.exports = api;
  }
  if (root) {
    root.PixelboxQuickStartTemplates = api;
  }
})(typeof globalThis !== 'undefined' ? globalThis : undefined, function quickStartTemplates() {
  const QUICK_SERVER_STARTER_PORT = 4173;

  function sanitizeProjectName(input) {
    return String(input || '')
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9-_]/g, '-')
      .replace(/-+/g, '-')
      .replace(/^-|-$/g, '');
  }

  function escapeHtml(value) {
    return String(value)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  }

  function projectDisplayName(projectPath, fallback = 'Pixelbox') {
    if (projectPath === '.') return fallback;
    return String(projectPath || '')
      .replace(/^projects\//, '')
      .replace(/\//g, ' ')
      .trim() || fallback;
  }

  function htmlStarterDocument(projectPath) {
    const rawTitle = projectPath === '.'
      ? 'Pixelbox Starter'
      : `${projectDisplayName(projectPath)} Starter`;
    const title = escapeHtml(rawTitle);
    return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title}</title>
    <style>
      :root {
        color-scheme: dark;
        font-family: Inter, ui-sans-serif, system-ui, -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif;
        background: #07111b;
        color: #f6fbff;
      }

      body {
        min-height: 100vh;
        margin: 0;
        display: grid;
        place-items: center;
        background:
          radial-gradient(circle at 20% 15%, rgba(127, 212, 255, 0.18), transparent 28%),
          radial-gradient(circle at 80% 80%, rgba(127, 242, 208, 0.12), transparent 32%),
          #07111b;
      }

      main {
        width: min(760px, calc(100vw - 40px));
      }

      p {
        max-width: 58ch;
        color: #acc4dc;
        line-height: 1.7;
      }

      h1 {
        margin: 0;
        font-size: clamp(2.4rem, 8vw, 5.6rem);
        line-height: 0.92;
      }
    </style>
  </head>
  <body>
    <main>
      <h1>${title}</h1>
      <p>This page was created from Pixelbox. Edit generated/landing.html, then refresh the preview.</p>
    </main>
  </body>
</html>
`;
  }

  function packageNameForProject(projectPath) {
    const rawName = projectPath === '.'
      ? 'pixelbox-starter'
      : projectDisplayName(projectPath);
    return sanitizeProjectName(rawName) || 'pixelbox-starter';
  }

  function serverStarterPage(projectPath, variant = 'server') {
    const projectLabel = projectDisplayName(projectPath);
    if (variant === 'surprise') {
      return {
        rawTitle: `${projectLabel} Launch Board`,
        body: `
    <main class="launch-board">
      <section>
        <p class="eyebrow">Pixelbox generated</p>
        <h1>${escapeHtml(projectLabel)} Launch Board</h1>
        <p class="lede">A tiny local product surface with live server state, generated by Pixelbox without installing dependencies.</p>
      </section>
      <section class="metric-grid" aria-label="Starter metrics">
        <article>
          <span>Loop</span>
          <strong>Idea -> app</strong>
        </article>
        <article>
          <span>Runtime</span>
          <strong>Node HTTP</strong>
        </article>
        <article>
          <span>Status</span>
          <strong id="clock">Loading</strong>
        </article>
      </section>
      <script>
        const clock = document.getElementById('clock');
        setInterval(() => {
          clock.textContent = new Date().toLocaleTimeString();
        }, 1000);
      </script>
    </main>`,
        extraCss: `
      .launch-board {
        display: grid;
        gap: 28px;
      }

      .eyebrow {
        margin: 0 0 12px;
        color: #9ce8cf;
        font: 700 0.74rem/1.2 ui-monospace, "SFMono-Regular", Menlo, monospace;
        letter-spacing: 0.12em;
        text-transform: uppercase;
      }

      .lede {
        font-size: 1.05rem;
      }

      .metric-grid {
        display: grid;
        grid-template-columns: repeat(3, minmax(0, 1fr));
        gap: 12px;
      }

      article {
        min-height: 120px;
        display: grid;
        align-content: space-between;
        border: 1px solid rgba(127, 212, 255, 0.22);
        border-radius: 18px;
        padding: 16px;
        background: rgba(255, 255, 255, 0.045);
      }

      article span {
        color: #acc4dc;
        font-size: 0.82rem;
      }

      article strong {
        font-size: 1.18rem;
      }

      @media (max-width: 680px) {
        .metric-grid {
          grid-template-columns: 1fr;
        }
      }`,
      };
    }

    return {
      rawTitle: projectPath === '.'
        ? 'Pixelbox Server Starter'
        : `${projectDisplayName(projectPath)} Server`,
      body: `
    <main>
      <h1>{{title}}</h1>
      <p>This local Node server was created from Pixelbox. Edit <code>server.js</code>, then refresh the preview.</p>
    </main>`,
      extraCss: '',
    };
  }

  function serverStarterDocument(projectPath, variant = 'server') {
    const page = serverStarterPage(projectPath, variant);
    const rawTitle = page.rawTitle;
    const title = escapeHtml(rawTitle);
    const body = page.body.replace(/\{\{title\}\}/g, title);
    return `const http = require('node:http');

const host = '127.0.0.1';
const port = Number(process.env.PORT || process.env.PIXELBOX_PORT || ${QUICK_SERVER_STARTER_PORT});

const page = ` + JSON.stringify(`<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title}</title>
    <style>
      :root {
        color-scheme: dark;
        font-family: Inter, ui-sans-serif, system-ui, -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif;
        background: #07111b;
        color: #f6fbff;
      }

      body {
        min-height: 100vh;
        margin: 0;
        display: grid;
        place-items: center;
        background:
          radial-gradient(circle at 18% 18%, rgba(127, 212, 255, 0.2), transparent 30%),
          radial-gradient(circle at 82% 75%, rgba(127, 242, 208, 0.14), transparent 32%),
          #07111b;
      }

      main {
        width: min(760px, calc(100vw - 40px));
      }

      h1 {
        margin: 0;
        font-size: clamp(2.4rem, 8vw, 5.6rem);
        line-height: 0.92;
      }

      p {
        max-width: 58ch;
        color: #acc4dc;
        line-height: 1.7;
      }

      code {
        color: #9ce8cf;
      }
${page.extraCss}
    </style>
  </head>
  <body>
${body}
  </body>
</html>
`) + `;

const server = http.createServer((req, res) => {
  res.writeHead(200, {
    'Content-Type': 'text/html; charset=utf-8',
    'Access-Control-Allow-Origin': '*',
    'Cache-Control': 'no-store',
  });
  res.end(page);
});

server.listen(port, host, () => {
  console.log(\`http://\${host}:\${port}\`);
});
`;
  }

  function starterPackageJson(existingContent, projectPath) {
    let packageJson = {
      name: packageNameForProject(projectPath),
      private: true,
      version: '0.1.0',
    };
    if (existingContent.trim()) {
      packageJson = JSON.parse(existingContent);
    }
    return {
      ...packageJson,
      scripts: {
        ...(packageJson.scripts || {}),
        dev: 'node server.js',
      },
    };
  }

  return {
    QUICK_SERVER_STARTER_PORT,
    escapeHtml,
    htmlStarterDocument,
    packageNameForProject,
    sanitizeProjectName,
    serverStarterDocument,
    serverStarterPage,
    starterPackageJson,
  };
});
